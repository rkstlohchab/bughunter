"""P9: evidence-backed checks across entity snapshots, staging quote tasks and research sessions.

This service analyzes observations already gathered by the desktop and its local tools.
It never attaches to processes, sends HTTP requests, or submits browser challenges.
"""
from __future__ import annotations

import hashlib
import http.client
import json
import math
import re
from .store import now

MAX_ENTITIES = 64
MAX_OBSERVATION_BYTES = 48_000
MAX_DELTAS = 32


def _digest(value) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('utf-8')).hexdigest()


def _observed_snapshot(value: dict) -> tuple[dict, dict[int, dict]]:
    """Accept snapshots generated by the local radar's /state endpoint.

    Keep only the whitelisted numeric fields. Never record the full raw dump.
    """
    if not isinstance(value, dict) or len(json.dumps(value, default=str)) > MAX_OBSERVATION_BYTES:
        raise ValueError('Provide a bounded radar snapshot JSON object.')
    if type(value.get('pid')) is not int or not 1 <= value['pid'] < 2**31:
        raise ValueError('Radar snapshots require an observed positive process PID.')
    entities = value.get('entities')
    if not isinstance(entities, list) or not 1 <= len(entities) <= MAX_ENTITIES:
        raise ValueError('Radar snapshots need 1–64 observed entities.')
    seen: dict[int, dict] = {}
    for item in entities:
        if not isinstance(item, dict) or type(item.get('id')) is not int or item['id'] < 0 or item['id'] >= 2**32:
            raise ValueError('Each entity needs a non-negative integer ID.')
        ident = item['id']
        if ident in seen:
            raise ValueError('Duplicate entity ID; cannot establish identity.')
        coords = {}
        for field in ('x', 'y'):
            val = item.get(field)
            if type(val) not in (float, int) or not math.isfinite(val) or abs(val) > 1_000_000:
                raise ValueError('Each entity needs finite bounded x/y coordinates.')
            coords[field] = float(val)
        for field in ('z', 'health'):
            if field in item:
                val = item[field]
                if type(val) not in (float, int) or not math.isfinite(val) or abs(val) > 1_000_000:
                    raise ValueError('Invalid optional numeric entity property.')
                coords[field] = float(val)
        if 'team' in item:
            if type(item['team']) is not int or not 0 <= item['team'] <= 1000:
                raise ValueError('Invalid team observation.')
            coords['team'] = item['team']
        seen[ident] = coords
    provenance = {'pid': value['pid'], 'entity_count': len(seen),
                  'sha256': _digest({'pid': value['pid'], 'entities': sorted((k, v) for k, v in seen.items())})}
    return provenance, seen


def compare_entity_snapshots(first: dict, second: dict) -> dict:
    """Determine observed entity changes. Does not infer unknown offsets or track across restarts."""
    a, left = _observed_snapshot(first)
    b, right = _observed_snapshot(second)
    common = sorted(left.keys() & right.keys())
    deltas = []
    for ident in common[:MAX_DELTAS]:
        x = round(right[ident]['x'] - left[ident]['x'], 5)
        y = round(right[ident]['y'] - left[ident]['y'], 5)
        distance = round(math.hypot(x, y), 5)
        rec = {'id': ident, 'delta_x': x, 'delta_y': y, 'distance_xy': distance,
               'moving': distance > 1e-5}
        if 'health' in left[ident] and 'health' in right[ident]:
            rec['health_delta'] = round(right[ident]['health'] - left[ident]['health'], 5)
        deltas.append(rec)
    return {'type': 'entity_snapshot_comparison', 'first': a, 'second': b,
            'common_count': len(common), 'new_count': len(right.keys() - left.keys()),
            'missing_count': len(left.keys() - right.keys()), 'deltas': deltas,
            'truncated': len(common) > MAX_DELTAS,
            'result': ('observed_changes' if any(d['moving'] or d.get('health_delta', 0) != 0 for d in deltas)
                       else 'entity_set_changed' if left.keys() != right.keys() else 'no_changes_observed'),
            'verification_level': 'decoded_observation_only',
            'limitations': 'IDs may be reused and supplied layouts may be wrong. No pointer stability, ESP accuracy, or cross-restart identity is proven.'}


def assess_staging_task(task: dict) -> dict:
    """Correlate existing quote-only HTTP gateway receipts, never replays checkout traffic."""
    if not isinstance(task, dict) or task.get('kind') != 'staging_price':
        raise ValueError('Select a dedicated staging price-integrity task.')
    report = task.get('result')
    if not isinstance(report, dict):
        raise ValueError('The task has no recorded staging evidence.')
    cases = report.get('cases')
    if not isinstance(cases, list) or len(cases) > 12:
        raise ValueError('Staging evidence is missing or malformed.')
    valid = []
    for entry in cases:
        if not isinstance(entry, dict) or entry.get('case') not in {'baseline','zero_price','negative_price','increased_price','discount','minimum_spend','coupon_stacking','quantity','client_price','tampered_zero','tampered_high'}:
            # Keep labels bounded, but do not assume only a particular suite version exists.
            if not isinstance(entry, dict) or not isinstance(entry.get('case'), str) or not re.fullmatch(r'[a-z_]{1,48}', entry['case']):
                raise ValueError('Malformed staged scenario label.')
        if type(entry.get('expected_total_minor')) is not int or type(entry.get('observed_total_minor')) is not int:
            raise ValueError('Missing integer quote totals.')
        evidence_ids = entry.get('evidence_ids')
        if not isinstance(evidence_ids, list) or not evidence_ids or any(not isinstance(s, str) or not 1 <= len(s) <= 128 for s in evidence_ids):
            raise ValueError('Case has no HTTP gateway receipt IDs.')
        consistent = entry['expected_total_minor'] == entry['observed_total_minor']
        valid.append({'case': entry['case'], 'matches_server_price': consistent, 'evidence_ids': evidence_ids[:10]})
    evidence = report.get('evidence_ids', [])
    has_receipts = isinstance(evidence, list) and bool(evidence)
    completed = task.get('status') == 'completed'
    enough = completed and has_receipts and len(valid) >= 3 and report.get('transactional_actions') == 0
    if not enough:
        assessment = 'insufficient_evidence'
    elif all(c['matches_server_price'] for c in valid):
        assessment = 'staging_price_invariants_passed'
    else:
        assessment = 'staging_price_integrity_review_needed'
    return {'type': 'staging_quote_evidence', 'task_id': task['id'],
            'project_id': task.get('project_id'), 'task_status': task.get('status'),
            'case_count': len(valid), 'cases': valid, 'evidence_ids': evidence[:30] if has_receipts else [],
            'assessment': assessment, 'verification_level': 'staging_quote_only',
            'limitations': 'No purchase, payment, production checkout, or unrelated application behavior was tested.'}


class VerificationP9:
    def __init__(self, app):
        self.app = app
        self.store = app.store

    def _project(self, project_id: str):
        if not isinstance(project_id, str) or not self.store.get('project', project_id):
            raise ValueError('Choose an existing project.')
        return project_id

    def _put(self, project_id, record):
        self.store.require_desktop_owner()
        if self.store.setting('emergency_stop', False):
            raise ValueError('Emergency stop is active.')
        row = self.store.put('p9_evidence_review', {'project_id': project_id,
               'created_on': now(), 'report': record})
        self.store.event('p9.evidence.reviewed', {'id': row['id'], 'project_id': project_id,
                                                 'type': record['type']})
        return row


    def capture_local(self, project_id, port=8787):
        """Fetch one actual local radar observation, without a browser CORS dependency.

        Fixed loopback host and /state path. No redirects, arbitrary URLs, or remote targets.
        """
        self._project(project_id)
        self.store.require_desktop_owner()
        if type(port) is not int or not 1024 <= port <= 65535:
            raise ValueError('Local radar port must be 1024–65535.')
        connection = http.client.HTTPConnection('127.0.0.1', port, timeout=3)
        try:
            connection.request('GET', '/state', headers={'Accept': 'application/json'})
            response = connection.getresponse()
            if response.status != 200 or 'application/json' not in response.getheader('Content-Type', ''):
                raise ValueError('Local radar did not return a usable JSON observation.')
            raw = response.read(MAX_OBSERVATION_BYTES + 1)
            if len(raw) > MAX_OBSERVATION_BYTES:
                raise ValueError('Radar observation exceeds size limit.')
            data = json.loads(raw)
            _observed_snapshot(data)
            return data
        finally:
            connection.close()

    def compare_game(self, project_id, first, second):
        project_id = self._project(project_id)
        result = compare_entity_snapshots(first, second)
        return self._put(project_id, result)

    def review_staging(self, project_id, task_id):
        project_id = self._project(project_id)
        task = self.store.get('work_task', task_id)
        if not task or task.get('project_id') != project_id:
            raise ValueError('Staging test does not belong to this project.')
        report = assess_staging_task(task)
        # Corroborate claimed receipt identifiers with gateway-owned traffic rows.
        # Imported/Burp observations alone cannot establish a staging execution.
        ids = {value for c in report['cases'] for value in c['evidence_ids']}
        ids.update(report['evidence_ids'])
        missing = []
        matched = {}
        manifest, quote = False, False
        for identifier in sorted(ids):
            item = self.store.get('traffic', identifier)
            if not item or item.get('project_id') != project_id or item.get('origin') != 'gateway' or item.get('trusted_observation') is not True:
                missing.append(identifier)
                continue
            request = item.get('request') or {}
            path = str(request.get('url','')).split('?', 1)[0]
            manifest |= request.get('method') == 'GET' and path.endswith('/.well-known/bughunter-price-audit.json')
            quote |= request.get('method') == 'POST' and path.endswith('/__bughunter__/quote')
            matched[identifier] = item
        # Inspect the actual persisted response instead of trusting copied
        # expected/observed numbers in the task summary. Never expose raw bodies.
        responses_match = True
        for case in (task.get('result') or {}).get('cases', []):
            confirmed = False
            for identifier in case['evidence_ids']:
                receipt = matched.get(identifier)
                if not receipt or not str((receipt.get('request') or {}).get('url','')).split('?',1)[0].endswith('/__bughunter__/quote'):
                    continue
                if (receipt.get('response') or {}).get('status') != 200:
                    continue
                try:
                    body = json.loads((receipt.get('response') or {}).get('body',''))
                except (ValueError, TypeError):
                    continue
                if isinstance(body, dict) and body.get('total_minor') == case['observed_total_minor'] and body.get('quote_only') is True and body.get('order_created') is False and body.get('payment_initiated') is False:
                    confirmed = True
                    break
            responses_match &= confirmed
        corroborated = not missing and manifest and quote and responses_match
        report['receipts_correlated'] = corroborated
        report['response_bodies_correlated'] = responses_match
        report['missing_receipt_count'] = len(missing)
        if not corroborated:
            report['assessment'] = 'insufficient_evidence'
        return self._put(project_id, report)

    def research_blockers(self, project_id):
        project_id = self._project(project_id)
        rows = self.store.list('research_browser_p3')
        result = []
        for row in rows:
            if row.get('project_id') != project_id:
                continue
            if row.get('status') not in ('waiting_for_human','interrupted'):
                continue
            result.append({'id': row['id'], 'status': row['status'],
                           'blocker': str(row.get('blocker') or '')[:120],
                           'next_action': 'Complete the challenge in the visible browser then resume' if row['status'] == 'waiting_for_human'
                           else 'Reopen browser, confirm source, then resume',
                           'capture_count': len(row.get('captured_ids') or [])})
        return result[:30]

    def list(self, project_id):
        project_id = self._project(project_id)
        return [{'id': row['id'], 'type': row['report']['type'],
                 'created_on': row['created_on'], 'result': row['report'].get('result', row['report'].get('assessment'))}
                for row in self.store.list('p9_evidence_review', project_id=project_id)[:50]]

    def get(self, project_id, id):
        project_id = self._project(project_id)
        row = self.store.get('p9_evidence_review', id)
        if not row or row.get('project_id') != project_id:
            raise ValueError('Evidence review is outside the selected project.')
        return row

    def summary(self, project_id):
        project_id = self._project(project_id)
        rows = self.list(project_id)
        return {'phase': 'P9', 'evidence_reviews': len(rows),
                'types': sorted(set(r['type'] for r in rows)),
                'results': rows[:10],
                'blocked_research_count': len(self.research_blockers(project_id)),
                'note': 'Only previously observed evidence is assessed. No external test, game-layout discovery, or CAPTCHA solution is initiated.'}

    def dispatch(self, method, p):
        if method == 'verification.p9.capture_local':
            return self.capture_local(p['project_id'],p.get('port',8787))
        if method == 'verification.p9.compare_entities':
            return self.compare_game(p['project_id'], p['first'], p['second'])
        if method == 'verification.p9.review_staging':
            return self.review_staging(p['project_id'], p['task_id'])
        if method == 'verification.p9.research_blockers':
            return self.research_blockers(p['project_id'])
        if method == 'verification.p9.list':
            return self.list(p['project_id'])
        if method == 'verification.p9.get':
            return self.get(p['project_id'], p['id'])
        if method == 'verification.p9.summary':
            return self.summary(p['project_id'])
        raise ValueError('Unknown P9 verification operation.')
