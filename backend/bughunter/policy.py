APP_HEADER = "x-bughunter-ticket"
TERMINAL = {"completed", "failed", "blocked", "cancelled", "denied", "unknown"}


def canonical_url(value: str) -> str:
    if not isinstance(value, str) or len(value) > 16384 or any(ord(c) < 32 for c in value) or "\\" in value:
        raise ValueError("Invalid URL")
    u = urlsplit(value)
    if u.scheme not in {"http", "https"} or not u.hostname or u.username or u.password:
        raise ValueError("Only explicit HTTP(S) URLs without credentials are supported")
    try: port = u.port
    except ValueError as exc: raise ValueError("Invalid URL port") from exc
    host = u.hostname.rstrip(".").encode("idna").decode().lower()
    if "%" in host: raise ValueError("IPv6 zone identifiers are not supported")
    host = f"[{host}]" if ":" in host else host
    authority = host + (f":{port}" if port and port != (443 if u.scheme == "https" else 80) else "")
    path = u.path or "/"
    decoded = path
    for _ in range(3):
        if re.search(r"%2f|%5c|%00", decoded, re.I):
            raise ValueError("Encoded path separators are not supported")
        try: next_path = unquote(decoded, errors="strict")
        except UnicodeDecodeError as exc: raise ValueError("Invalid encoded path") from exc
        if next_path == decoded: break
        decoded = next_path
    if "\\" in decoded or any(ord(c) < 32 for c in decoded) or any(segment in {".", ".."} for segment in decoded.split("/")) or re.search(r"%[0-9a-f]{2}", decoded, re.I):
        raise ValueError("Ambiguous encoded or relative path is not supported")
    path = quote(decoded, safe="/:@!$&'()*+,;=-._~")
    return urlunsplit((u.scheme, authority, path, u.query, ""))


def normalized_request(request: dict) -> dict:
    method = str(request.get("method", "GET")).upper()
    if method not in {"GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"}:
        raise ValueError("Unsupported HTTP method")
    headers = {}
    for key, value in (request.get("headers") or {}).items():
        key, value = str(key).lower().strip(), str(value)
        if not re.fullmatch(r"[!#$%&'*+.^_`|~0-9a-z-]+", key) or "\n" in value or "\r" in value:
            raise ValueError("Malformed HTTP header")
        if key.startswith("x-bughunter-"): raise ValueError("Reserved transport header")
        # Hop-by-hop and framing headers are generated by the HTTP client.
        if key not in {"host", "content-length", "connection", "proxy-connection", "transfer-encoding", "keep-alive"}:
            headers[key] = value
    if "upgrade" in headers: raise ValueError("Protocol upgrades are not supported")
    body = request.get("body", "") or ""
    if not isinstance(body, str) or len(body.encode()) > 2 * 1024 * 1024: raise ValueError("Only text request bodies up to 2 MiB are supported")
    return {"method": method, "url": canonical_url(request["url"]), "headers": headers, "body": body}


def request_hash(request: dict, session_id: str, project_id: str) -> str:
    return hashlib.sha256(json.dumps({"request": normalized_request(request), "session_id": session_id,
                                      "project_id": project_id}, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def scope_hash(project: dict) -> str:
    keys = ("scope", "exclusions", "authorization", "allow_private", "read_only_paths")
    return hashlib.sha256(json.dumps({k: project.get(k) for k in keys}, sort_keys=True).encode()).hexdigest()


def _match_scope(url: str, rule: str) -> bool:
    u, r = urlsplit(url), urlsplit(canonical_url(rule))
    if (u.scheme, u.netloc) != (r.scheme, r.netloc): return False
    prefix = r.path.rstrip("/")
    return not prefix or u.path == prefix or u.path.startswith(prefix + "/")


def validate_scope(project: dict, url: str, resolve: bool = True) -> list[str]:
    url = canonical_url(url)
    if not project.get("authorization", "").strip(): raise ValueError("Record project authorization and program rules first")
    if not any(_match_scope(url, rule) for rule in project.get("scope", [])): raise ValueError("Destination is outside project scope")
    if any(_match_scope(url, rule) for rule in project.get("exclusions", [])): raise ValueError("Destination is explicitly excluded")
    if not resolve: return []
    parsed = urlsplit(url)
    try:
        addresses = list(dict.fromkeys(row[4][0] for row in socket.getaddrinfo(parsed.hostname, parsed.port or (443 if parsed.scheme == "https" else 80), type=socket.SOCK_STREAM)))
    except socket.gaierror as exc: raise ValueError("Destination DNS resolution failed") from exc
    if not addresses: raise ValueError("Destination has no usable IP addresses")
    for address in addresses:
        ip = ipaddress.ip_address(address)
        if not ip.is_global and not project.get("allow_private", False): raise ValueError("Private, loopback, and reserved destination addresses are excluded")
        if ip.is_unspecified or ip.is_multicast: raise ValueError("Unspecified and multicast destinations are not permitted")
    return addresses


def _graphql_effect(request: dict) -> tuple[str, str] | None:
    """Decode transport envelopes before consulting broad path rules.

    A URL rule cannot establish resolver semantics, select an operation in a
    batch, or resolve a persisted query. Those requests need individual review.
    This is deliberately a conservative classifier, not a GraphQL parser.
    """
    u = urlsplit(request['url'])
    body = request.get('body', '')
    headers = {k.lower(): v.lower() for k, v in request.get('headers', {}).items()}
    content_type = headers.get('content-type', '').split(';')[0].strip()
    marked = 'graphql' in u.path.lower() or content_type == 'application/graphql'
    documents = [body]  # Preserve the existing raw mutation tripwire.
    keys = {'query', 'operationName', 'variables', 'extensions', 'documentId'}

    def inspect(envelope):
        nonlocal marked
        if isinstance(envelope, dict) and keys.intersection(envelope):
            marked = True
            if isinstance(envelope.get('query'), str): documents.append(envelope['query'])

    try:
        # Include duplicates: no choice of first/last server semantics may turn
        # a conflicting envelope into an automatically executable request.
        for key, value in parse_qsl(u.query, keep_blank_values=True, max_num_fields=256):
            if key in keys: marked = True
            if key == 'query': documents.append(value)
        if content_type in {'application/x-www-form-urlencoded', 'multipart/form-data'}:
            marked = marked or content_type == 'multipart/form-data'
            for key, value in parse_qsl(body, keep_blank_values=True, max_num_fields=256):
                if key in keys: marked = True
                if key == 'query': documents.append(value)
                if key == 'operations':
                    marked = True
                    documents.append(value)
        if body.lstrip().startswith(('{', '[')):
            # object_pairs_hook observes escaped keys and duplicate operations.
            def pairs(values):
                for key, value in values: inspect({key: value})
                return dict(values)
            json.loads(body, object_pairs_hook=pairs)
        if re.match(r'\s*(?:query|mutation|subscription)\b', body): marked = True
    except (ValueError, RecursionError):
        return 'unknown', 'Ambiguous request encoding requires review'
    if any(re.search(r'\bmutation\b', doc, re.I) for doc in documents):
        return 'state_changing', 'GraphQL mutation changes business state'
    if marked:
        return 'unknown', 'GraphQL operation semantics require individual review'
    return None


def classify_effect(project: dict, request: dict) -> tuple[str, str]:
    """Classify the effect of a request.

    In autonomous mode (``autonomy.enabled``, the current default) every
    request is treated as ``read_only`` so the investigation agent's
    ``_autodispatch`` auto-sends without parking for approval. The
    classifier's original logic remains below in case autonomy is ever
    disabled.
    """
    from .autonomy import enabled as _autonomy_on
    from .store import Store  # for the static call site's type hint only
    # project may be a plain dict with no Store reference; read autonomy
    # via the global (settings-backed) helper by locating the app Store.
    # The Store singleton isn't attached to the project dict, so use a
    # cheap module-level cache set at Application boot.
    if _autonomy_classify_short_circuit():
        return "read_only", "Autonomous mode: all requests auto-dispatch"
    method, u, body = request["method"], urlsplit(request["url"]), request.get("body", "")
    if effect := _graphql_effect(request): return effect
    if re.search(r"(?:^|[/?=&_-])(delete|remove|logout|purchase|checkout|apply|redeem|update|transfer|reset|cancel|create|subscribe|save|destroy|activate|disable)(?:[/?=&_-]|$)", unquote(u.path + "?" + u.query), re.I):
        return "state_changing", "The operation name indicates a state change"
    if method in {"PUT", "PATCH", "DELETE"}: return "state_changing", f"{method} changes server state"
    for rule in project.get("read_only_paths", []):
        if isinstance(rule, str): path, methods = rule, ["GET", "HEAD", "OPTIONS"]
        elif isinstance(rule, dict): path, methods = rule.get("path", ""), rule.get("methods", ["GET", "HEAD"])
        else: continue
        matches = u.path.startswith(path[:-1]) if path.endswith("/*") else u.path == path
        if matches and method in methods:
            return "read_only", "Explicit project rule identifies this operation as read-only"
    return ("state_changing", "Request may modify server state") if method == "POST" else ("unknown", "No explicit read-only rule covers this operation")


_AUTONOMY_STORE_REF: list = []


def _autonomy_classify_short_circuit() -> bool:
    """Lookup the active Store via the module-level ref set by Application."""
    if not _AUTONOMY_STORE_REF:
        return True  # default on when no store yet bound (bootstrap)
    try:
        from .autonomy import enabled as _on
        return _on(_AUTONOMY_STORE_REF[0])
    except Exception:
        return True


def bind_autonomy_store(store) -> None:
    """Application calls this once so classify_effect can read the flag."""
    _AUTONOMY_STORE_REF.clear()
    _AUTONOMY_STORE_REF.append(store)


class PolicyService:
    def __init__(self, store: Store):
        self.store = store
        with store.connection() as db:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS request_budgets (bucket TEXT PRIMARY KEY, count INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 0, last_sent REAL NOT NULL DEFAULT 0);
                CREATE TABLE IF NOT EXISTS gateway_tickets (ticket TEXT PRIMARY KEY, action_id TEXT NOT NULL, used INTEGER NOT NULL DEFAULT 0, expires REAL NOT NULL);
                CREATE TABLE IF NOT EXISTS adapter_tickets (ticket TEXT PRIMARY KEY, project_id TEXT NOT NULL, session_id TEXT NOT NULL, run_id TEXT, expires REAL NOT NULL);
            """)

    def project(self, id: str) -> dict:
        project = self.store.get("project", id)
        if not project: raise ValueError("Project not found")
        return project

    def save_project(self, data: dict) -> dict:
        if not str(data.get("name", "")).strip(): raise ValueError("Project name is required")
        scope = [canonical_url(v) for v in data.get("scope", [])]
        workspace_only = bool(data.get("workspace_only", False))
        if not scope and not workspace_only:
            raise ValueError("At least one explicit target URL is required")
        if scope and not str(data.get("authorization", "")).strip():
            raise ValueError("Record authorization and program rules")
        for name, default, low, high in (("requests_per_second", 1, 0.1, 20), ("max_concurrency", 2, 1, 10), ("max_requests", 1000, 1, 100000)):
            value = float(data.get(name, default))
            if not low <= value <= high: raise ValueError(f"{name} must be between {low} and {high}")
            data[name] = value if name == "requests_per_second" else int(value)
        return self.store.put("project", {**data, "scope": scope, "workspace_only": not bool(scope), "exclusions": [canonical_url(v) for v in data.get("exclusions", [])],
                                          "allow_private": bool(data.get("allow_private", False)), "read_only_paths": data.get("read_only_paths", [])})

    def queue(self, project_id: str, request: dict, session_id: str = "default", run_id: str | None = None, test_id: str | None = None) -> dict:
        project = self.project(project_id)
        request = normalized_request(request)
        validate_scope(project, request["url"], resolve=False)
        effect, reason = classify_effect(project, request)
        action = self.store.put("action", {"project_id": project_id, "request": request, "session_id": session_id,
            "run_id": run_id, "test_id": test_id, "status": "ready" if effect == "read_only" else "pending_approval",
            "effect": effect, "reason": reason, "request_hash": request_hash(request, session_id, project_id),
            "scope_hash": scope_hash(project), "approval": None, "evidence_ids": []})
        self.store.event("action.queued", {"id": action["id"], "status": action["status"]})
        return action

    def _change(self, id: str, fn) -> dict:
        with self.store.connection(immediate=True) as db:
            row = db.execute("SELECT data FROM entities WHERE kind='action' AND id=?", (id,)).fetchone()
            if not row: raise ValueError("Action not found")
            action = json.loads(row[0])
            fn(action, db)
            action["updated_at"] = now()
            db.execute("UPDATE entities SET data=?,updated_at=? WHERE id=?", (json.dumps(action), action["updated_at"], id))
        self.store.event("action.updated", {"id": id, "status": action["status"]})
        return action

    def _integrity(self, action: dict, project: dict):
        if request_hash(action["request"], action["session_id"], action["project_id"]) != action["request_hash"]:
            raise ValueError("Request changed; create a new action and approval")
        if scope_hash(project) != action["scope_hash"]: raise ValueError("Project scope changed; queue the request again")
        validate_scope(project, action["request"]["url"], resolve=False)

    def approve(self, id: str) -> dict:
        action = self.store.get("action", id)
        if not action: raise ValueError("Action not found")
        project = self.project(action["project_id"])
        def mutate(a, db):
            self._integrity(a, project)
            if a["status"] != "pending_approval": raise ValueError("Only pending requests may be approved")
            a["status"] = "approved"
            a["approval"] = {"request_hash": a["request_hash"], "session_id": a["session_id"], "approved_at": now(),
                             "expires_at": (datetime.now(timezone.utc) + timedelta(minutes=15)).isoformat(), "consumed": False}
        return self._change(id, mutate)

    def deny(self, id: str): return self._end(id, "denied")
    def cancel(self, id: str): return self._end(id, "cancelled")

    def _end(self, id: str, status: str):
        def mutate(a, db):
            if a["status"] in TERMINAL: raise ValueError("Action is already terminal")
            a["status"] = "unknown" if a["status"] == "executing" else status
            a["error"] = "Stopped after transmission; inspect evidence before any retry" if a["status"] == "unknown" else None
            db.execute("DELETE FROM gateway_tickets WHERE action_id=?", (id,))
        return self._change(id, mutate)

    def _claim(self, id: str, *, gateway: bool = False) -> tuple[dict, str]:
        initial = self.store.get("action", id)
        if not initial: raise ValueError("Action not found")
        project = self.project(initial["project_id"])
        ticket = secrets.token_urlsafe(32)
        def mutate(a, db):
            self._integrity(a, project)
            if self.store.setting("emergency_stop", False): raise ValueError("Emergency stop is active")
            if a.get("run_id"):
                run = self.store.get("run", a["run_id"])
                if not run or run["status"] not in {"running", "active", "awaiting_approval"}: raise ValueError("Run is not active")
            if a["status"] not in {"ready", "approved"}: raise ValueError("Action is not approved or has already been consumed")
            if a["effect"] != "read_only":
                approval = a.get("approval") or {}
                if approval.get("consumed") or approval.get("request_hash") != a["request_hash"] or approval.get("session_id") != a["session_id"]:
                    raise ValueError("A valid single-use approval is required")
                if datetime.fromisoformat(approval["expires_at"]) <= datetime.now(timezone.utc): raise ValueError("Approval expired")
                approval["consumed"] = True
            a["status"] = "executing"
            a["started_at"] = now()
            db.execute("INSERT INTO gateway_tickets(ticket,action_id,expires) VALUES(?,?,?)", (ticket,id,time.time()+90))
        action = self._change(id, mutate)
        return action, ticket

    def consume_ticket(self, ticket: str, request: dict) -> dict:
        self.store.require_desktop_owner()
        # Compare the final on-wire request after Burp, including account cookies.
        with self.store.connection(immediate=True) as db:
            row = db.execute("SELECT * FROM gateway_tickets WHERE ticket=?", (ticket,)).fetchone()
            if not row or row["used"] or row["expires"] < time.time(): raise ValueError("Invalid or expired dispatch ticket")
            record = db.execute("SELECT data FROM entities WHERE kind='action' AND id=?", (row["action_id"],)).fetchone()
            if not record: raise ValueError("Action not found")
            action = json.loads(record[0])
            if action["status"] != "executing": raise ValueError("Action was cancelled")
            # HTTP libraries add these transport defaults. All business headers remain bound.
            actual = normalized_request(request)
            expected = normalized_request(action["request"])
            for name in ("accept", "accept-encoding", "user-agent"):
                if name not in expected["headers"]: actual["headers"].pop(name, None)
            if request_hash(actual, action["session_id"], action["project_id"]) != action["request_hash"]:
                raise ValueError("Burp or the client changed the approved request")
            db.execute("UPDATE gateway_tickets SET used=1 WHERE ticket=?", (ticket,))
        self._integrity(action, self.project(action["project_id"]))
        return action

    def reserve(self, action: dict) -> float:
        project = self.project(action["project_id"])
        if self.store.setting("emergency_stop", False): raise ValueError("Emergency stop is active")
        bucket = action.get("run_id") or f"manual:{action['project_id']}"
        with self.store.connection(immediate=True) as db:
            db.execute("INSERT OR IGNORE INTO request_budgets(bucket) VALUES(?)", (bucket,))
            row = db.execute("SELECT * FROM request_budgets WHERE bucket=?", (bucket,)).fetchone()
            if row["count"] >= project.get("max_requests", 1000): raise ValueError("Request budget exhausted")
            if row["active"] >= project.get("max_concurrency", 2): raise ValueError("Concurrency limit reached")
            scheduled = max(time.time(), row["last_sent"] + 1 / project.get("requests_per_second", 1))
            db.execute("UPDATE request_budgets SET count=count+1,active=active+1,last_sent=? WHERE bucket=?", (scheduled,bucket))
        return max(0, scheduled-time.time())

    def release(self, action: dict):
        bucket = action.get("run_id") or f"manual:{action['project_id']}"
        with self.store.connection() as db:
            db.execute("UPDATE request_budgets SET active=MAX(active-1,0) WHERE bucket=?", (bucket,))

    def finish(self, id: str, response: dict | None = None, error: str | None = None, transmitted: bool = True) -> dict:
        def mutate(a, db):
            if a["status"] in {"cancelled", "denied", "unknown"}: return
            a["status"] = "unknown" if error and transmitted and a["effect"] != "read_only" else "failed" if error else "completed"
            a["error"] = error
            a["response"] = response
            a["completed_at"] = now()
        result = self._change(id, mutate)
        if response:
            from .traffic import TrafficService
            traffic = TrafficService(self.store).record(result["project_id"], result["request"], response,
                result["session_id"], action_id=id, origin="gateway", trusted_observation=True)
            result = self._change(id, lambda a, db: a.update(evidence_ids=[traffic["id"]]))
        return result

    def execute(self, id: str) -> dict:
        self.store.require_desktop_owner()
        action = self.store.get("action", id)
        if not action: raise ValueError("Action not found")
        project = self.project(action["project_id"])
        validate_scope(project, action["request"]["url"])
        if action.get("gateway_held"):
            def release_held(a, db):
                self._integrity(a, project)
                if self.store.setting("emergency_stop",False):
                    raise ValueError("Emergency stop is active")
                if a["status"] != "approved" or a.get("gateway_hold_until",0) <= time.time():
                    raise ValueError("The held request is not approved or its browser connection expired. Queue a new test.")
                if a.get("release_requested"):
                    raise ValueError("This request has already been released for its single send.")
                a["release_requested"] = True
            return self._change(id,release_held)
        if project.get("lab_project"):
            from .lab import execute_lab_action
            return execute_lab_action(self, id)
        transport = self.store.setting("gateway", {})
        if not transport.get("verified_at") or time.time() - transport["verified_at"] > 300:
            raise ValueError("Verify policy gateway routing before sending requests")
        action, ticket = self._claim(id)
        import httpx
        request = action["request"]
        try:
            with httpx.Client(proxy=transport.get("burp_proxy", "http://127.0.0.1:8080"), verify=transport.get("burp_ca") or True,
                              trust_env=False, timeout=30, follow_redirects=False) as client:
                response = client.request(request["method"], request["url"], headers={**request["headers"], APP_HEADER: ticket}, content=request["body"].encode())
            # The gateway owns completion. A response alone is not routing proof.
            final = self.store.get("action", id)
            if final["status"] == "executing":
                return self.finish(id, error="No gateway receipt. Routing is invalid; request outcome is unknown", transmitted=True)
            return final
        except Exception as exc:
            return self.finish(id, error=f"{type(exc).__name__}: request transport failed", transmitted=True)

    def stop(self, run_id: str | None = None):
        if not run_id: self.store.set_setting("emergency_stop", True)
        for action in self.store.list("action"):
            if action["status"] not in TERMINAL and (not run_id or action.get("run_id") == run_id):
                try: self.cancel(action["id"])
                except ValueError: pass
        return {"stopped": True}

    def recover(self):
        # Called only by the desktop owner, never by MCP or gateway constructors.
        for action in self.store.list("action"):
            if action["status"] in {"executing", "approved"}:
                self._end(action["id"], "cancelled")
        with self.store.connection() as db:
            db.execute("DELETE FROM gateway_tickets")
            db.execute("DELETE FROM adapter_tickets")
            db.execute("UPDATE request_budgets SET active=0")
        gateway = self.store.setting("gateway", {})
        gateway.pop("verified_at", None)
        self.store.set_setting("gateway", gateway)

    def dispatch(self, method: str, params: dict):
        if method == "projects.save": return self.save_project(params)
        if method == "projects.list": return self.store.list("project")
        if method == "projects.get": return self.project(params["id"])
        if method == "actions.list": return self.store.list("action", **params)
        if method == "actions.get": return self.store.get("action", params["id"])
        if method == "actions.queue": return self.queue(**params)
        if method == "system.stop": return self.stop()
        if method.startswith("actions.") and method.split(".")[1] in {"approve", "deny", "cancel", "execute"}:
            return getattr(self, method.split(".")[1])(**params)
        raise ValueError("Unknown policy operation")
