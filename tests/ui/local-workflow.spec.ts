import {openTool, openWeb} from './navigation';
import { test, expect } from '@playwright/test';
import { spawn, type ChildProcess } from 'node:child_process';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import { createServer } from 'node:net';

test('real backend: lesson to approved shop test to evidence report and reusable learning', async ({ page }) => {
  test.setTimeout(90000);
  const root = await mkdtemp(join(tmpdir(),'bughunter-ui-'));
  const token = randomBytes(24).toString('hex');
  const reserve = createServer();
  await new Promise<void>(r => reserve.listen(0,'127.0.0.1',r));
  const port = (reserve.address() as { port:number }).port;
  await new Promise<void>(r => reserve.close(() => r()));
  let process: ChildProcess | undefined;
  let backendLog = '';
  try {
    const fixture = join(root,'commerce-lesson.md');
    await writeFile(fixture,'# Coupon eligibility\nExcluded products must keep their server-calculated price. A coupon applied to an excluded product is a hypothesis until the server accepts the discount. Compare with a fixed control.');
    process = spawn(resolve('backend/.venv/bin/python'),['-m','bughunter','--http','--port',String(port),'--data-dir',root],{cwd:resolve('backend'),env:{...globalThis.process.env,BUGHUNTER_RPC_TOKEN:token},stdio:['ignore','ignore','pipe']});
    process.stderr?.on('data',data => { backendLog += data.toString(); });
    await expect.poll(async () => { try { return (await fetch(`http://127.0.0.1:${port}/rpc`)).status; } catch { return 0; } }).toBe(405);
    expect((await fetch(`http://127.0.0.1:${port}/rpc`,{method:'POST',body:'{}'})).status).toBe(401);
    expect((await fetch(`http://127.0.0.1:${port}/rpc`,{method:'POST',body:'{}',headers:{Authorization:`Bearer ${token}`,Origin:'https://untrusted.example'}})).status).toBe(403);
    // Forward UI RPC to a real isolated backend, with no mocked application results.
    await page.route('http://127.0.0.1:8765/rpc',async route => {
      const headers = { 'Access-Control-Allow-Origin':'*', 'Access-Control-Allow-Headers':'Authorization, Content-Type', 'Access-Control-Allow-Methods':'POST, OPTIONS' };
      if (route.request().method() === 'OPTIONS') { await route.fulfill({status:204,headers}); return; }
      const response = await fetch(`http://127.0.0.1:${port}/rpc`,{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:route.request().postData()});
      await route.fulfill({status:response.status,body:await response.text(),headers:{...headers,'Content-Type':'application/json'}});
    });
    await page.goto('/');
  await openWeb(page);
    await page.getByRole('button',{name:'Try the disposable test shop'}).click();
    await expect(page.getByText('Disposable test-shop project created.',{exact:false})).toBeVisible();
    await page.getByRole('button',{name:'Library',exact:true}).click();
    await page.getByRole('button',{name:'Upload / add link',exact:true}).click();
    await page.getByRole('button',{name:'Large course / folder',exact:true}).click();
    await page.getByLabel('Absolute file path').fill(fixture);
    await page.getByRole('dialog').getByRole('button',{name:'Import resource',exact:true}).click();
    await expect(page.getByRole('button',{name:'commerce-lesson',exact:true})).toBeVisible({timeout:15000});
    await page.getByLabel('Search knowledge').fill('coupon eligibility');
    await page.getByRole('button',{name:'Search',exact:true}).click();
    await expect(page.getByText('Excluded products must keep',{exact:false})).toBeVisible();
    await openWeb(page, 'Captured requests');
    await page.locator('.traffic-row').filter({hasText:'/vulnerable/cart'}).click();
    await page.getByRole('button',{name:'Suggest checks',exact:true}).click();
    await page.getByRole('button',{name:'Suggested checks',exact:true}).click();
    await page.locator('.test-row').filter({hasText:'Check coupon eligibility on excluded items'}).click();
    await expect(page.getByText('Expected secure behavior', {exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Review this check'}).click();
    await page.getByRole('button',{name:'Add to approvals',exact:true}).click();
    await page.locator('.test-row').filter({hasText:'pending approval'}).click();
    await expect(page.getByRole('button',{name:'Send once'})).toHaveCount(0);
    await page.getByRole('button',{name:'Approve exact request'}).click();
    await page.getByRole('button',{name:'Send once'}).click();
    await page.getByRole('button',{name:'Assess evidence'}).click();
    await expect(page.getByRole('button',{name:'Excluded item received coupon',exact:true})).toBeVisible();
    await page.getByLabel('Export Excluded item received coupon').selectOption('json');
    const exported = page.getByRole('dialog',{name:'Exported report'});
    await expect(exported).toContainText('"status": "confirmed"');
    await expect(exported).toContainText('"trusted_observation": true');
    await expect(exported).toContainText('commerce-lesson');
    await page.screenshot({path:test.info().outputPath('verified-report.png'),fullPage:true});
    await page.getByRole('button',{name:'Done',exact:true}).click();
    await page.getByRole('button',{name:'Save as lesson'}).click();
    await expect(page.getByText('Redacted finding saved to the learning library.')).toBeVisible();
    await openTool(page, 'Knowledge graph');
    await expect(page.locator('.graph-node.type-observation')).toHaveCount(1);
    await openWeb(page, 'Targets & scope');
    await page.getByRole('button',{name:'Delete project',exact:true}).click();
    await expect(page.getByRole('dialog')).toContainText('Your learning library');
    await page.getByRole('dialog').getByRole('button',{name:'Delete project',exact:true}).click();
    await expect(page.getByText('0 projects',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Library',exact:true}).click();
    await expect(page.getByRole('button',{name:'commerce-lesson',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'commerce-lesson',exact:true}).click();
    await page.getByRole('button',{name:'Free source storage',exact:true}).click();
    await page.getByRole('button',{name:'Keep knowledge and release',exact:true}).click();
    await expect(page.getByText('Original released · extracted knowledge retained',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Create training example',exact:true}).click();
    const example = page.getByRole('dialog',{name:'Curate a training example'});
    await example.getByLabel('Question',{exact:true}).fill('What confirms a coupon eligibility bug?');
    await example.getByLabel('Checked answer',{exact:true}).fill('A server-accepted excluded product discount, compared with the fixed control.');
    await example.getByLabel('I checked this answer against the cited evidence.').check();
    await example.getByLabel('I have permission to use this example for model training.').check();
    await example.getByRole('button',{name:'Save example',exact:true}).click();
    await expect(example).toHaveCount(0);
    await page.getByRole('button',{name:'Close dialog',exact:true}).click();
    await page.getByText('Export and storage',{exact:true}).click();
    await page.getByText('How learning and storage work',{exact:true}).click();
    await page.getByRole('button',{name:'Export portable knowledge',exact:true}).click();
    await page.getByRole('button',{name:'Create knowledge export',exact:true}).click();
    await expect(page.getByLabel('Saved ZIP path')).toHaveValue(/knowledge_.+\.zip$/);
    await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  } finally {
    process?.kill('SIGTERM');
    if (process?.exitCode === null) await new Promise(r => { process!.once('exit',r); setTimeout(r,3000); });
    await rm(root,{recursive:true,force:true});
    await test.info().attach('backend.log',{body:backendLog,contentType:'text/plain'});
  }
});
